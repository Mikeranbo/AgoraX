// Each seed event's gallery: downloads the photos and videos listed in scripts/media-sources.json
// once (into .cache/media, not committed), then writes into public/media/<slug>/:
//   photos as WebP at 640, 1280 and 1920 px (never enlarged): <n>-<w>.webp
//   the video as a short muted loop (8 s, 720p, H.264, no sound): video.mp4, plus a WebP poster
// and the manifest the app reads (src/data/mediaManifest.ts) and public/media/CREDITS.md.
// Files that already exist are kept; pass --force to rewrite them.
//
// Run: node scripts/build-media.mjs   (needs ffmpeg on PATH, or FFMPEG=<path to ffmpeg>)
import { mkdir, readFile, writeFile, access } from 'node:fs/promises';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import path from 'node:path';
import sharp from 'sharp';

const run = promisify(execFile);
const ROOT = path.resolve(import.meta.dirname, '..');
const CACHE = path.join(ROOT, '.cache', 'media');
const OUT = path.join(ROOT, 'public', 'media');
const WIDTHS = [640, 1280, 1920];
const POSTER_WIDTHS = [640, 1280];
const LOOP_SECONDS = 8;
const FFMPEG = process.env.FFMPEG || 'ffmpeg';
const FORCE = process.argv.includes('--force');

const { events, checked } = JSON.parse(await readFile(path.join(ROOT, 'scripts', 'media-sources.json'), 'utf8'));
const exists = (p) => access(p).then(() => true, () => false);
const fresh = async (file) => FORCE || !(await exists(file));

async function download(url, file) {
  if (await exists(file)) return file;
  const res = await fetch(url, { headers: { 'User-Agent': 'agorax-build' } });
  if (!res.ok) throw new Error(`${url}: download failed (${res.status})`);
  await writeFile(file, Buffer.from(await res.arrayBuffer()));
  return file;
}

async function image(slug, n, item) {
  const src = await download(`https://images.unsplash.com/photo-${item.id}?w=1920&q=90&fm=jpg&fit=max`, path.join(CACHE, `${item.id}.jpg`));
  const meta = await sharp(src).metadata();
  const widths = WIDTHS.filter((w) => w <= meta.width);
  if (widths.at(-1) !== meta.width && meta.width < WIDTHS.at(-1)) widths.push(meta.width);
  for (const w of widths) {
    const file = path.join(OUT, slug, `${n}-${w}.webp`);
    if (await fresh(file)) await sharp(src).resize({ width: w, withoutEnlargement: true }).webp({ quality: 74 }).toFile(file);
  }
  const width = widths.at(-1);
  return {
    kind: 'image',
    base: `/media/${slug}/${n}`,
    widths,
    width,
    height: Math.round((meta.height * width) / meta.width),
    credit: `Photo: ${item.author} / Unsplash`,
    link: item.page,
  };
}

async function video(slug, item) {
  const src = await download(item.file, path.join(CACHE, `pexels-${item.id}.mp4`));
  const out = path.join(OUT, slug, 'video.mp4');
  if (await fresh(out)) {
    // A short silent loop: the first seconds, 720p wide, small enough to autoplay on phones.
    await run(FFMPEG, ['-y', '-loglevel', 'error', '-i', src, '-t', String(LOOP_SECONDS), '-an', '-vf', 'scale=1280:-2,fps=25',
      '-c:v', 'libx264', '-preset', 'slow', '-crf', '29', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', out]);
  }
  const frame = path.join(CACHE, `pexels-${item.id}-poster.png`);
  if (FORCE || !(await exists(frame))) await run(FFMPEG, ['-y', '-loglevel', 'error', '-ss', '0.5', '-i', out, '-frames:v', '1', frame]);
  const meta = await sharp(frame).metadata();
  for (const w of POSTER_WIDTHS) {
    const file = path.join(OUT, slug, `video-poster-${w}.webp`);
    if (await fresh(file)) await sharp(frame).resize({ width: w, withoutEnlargement: true }).webp({ quality: 72 }).toFile(file);
  }
  return {
    kind: 'video',
    src: `/media/${slug}/video.mp4`,
    poster: `/media/${slug}/video-poster`,
    posterWidths: POSTER_WIDTHS,
    width: meta.width,
    height: meta.height,
    credit: `Video: ${item.author} / Pexels`,
    link: item.page,
  };
}

await mkdir(CACHE, { recursive: true });
const manifest = {};
const slugs = Object.keys(events);
for (let i = 0; i < slugs.length; i += 4) {
  await Promise.all(
    slugs.slice(i, i + 4).map(async (slug) => {
      await mkdir(path.join(OUT, slug), { recursive: true });
      let n = 0;
      const items = [];
      for (const item of events[slug]) items.push(item.type === 'video' ? await video(slug, item) : await image(slug, ++n, item));
      manifest[slug] = items;
    }),
  );
  console.log(`${Math.min(i + 4, slugs.length)}/${slugs.length}`);
}

const ordered = Object.fromEntries(slugs.map((s) => [s, manifest[s]]));
await writeFile(
  path.join(ROOT, 'src', 'data', 'mediaManifest.ts'),
  `// Generated by scripts/build-media.mjs from scripts/media-sources.json. Do not edit by hand.\n` +
    `// Each seed event's gallery in order; the first item is the cover. Files live in public/media.\n\n` +
    `export interface SeedImage {\n  kind: 'image';\n  /** <base>-<width>.webp for every width. */\n  base: string;\n  widths: number[];\n  width: number;\n  height: number;\n  credit: string;\n  link: string;\n}\n\n` +
    `export interface SeedVideo {\n  kind: 'video';\n  src: string;\n  /** <poster>-<width>.webp for every posterWidth. */\n  poster: string;\n  posterWidths: number[];\n  width: number;\n  height: number;\n  credit: string;\n  link: string;\n}\n\n` +
    `export type SeedMedia = SeedImage | SeedVideo;\n\n` +
    `export const MEDIA_MANIFEST: Record<string, SeedMedia[]> = ${JSON.stringify(ordered, null, 2)};\n`,
);

const rows = slugs.flatMap((slug) =>
  events[slug].map((item) => `| \`media/${slug}\` | ${item.type} | [${item.author}](${item.profile}) | [source](${item.page}) | ${item.licence} |`),
);
await writeFile(
  path.join(OUT, 'CREDITS.md'),
  `# Event photo and video credits\n\nPhotos are from [Unsplash](https://unsplash.com) (Unsplash License; each checked on ${checked} as free, ` +
    `not Unsplash+). Videos are from [Pexels](https://www.pexels.com) (Pexels License), shortened to silent loops. Both licences ` +
    `allow commercial use without permission; the credit is given anyway. Files are served from this site, never hotlinked. ` +
    `The list is scripts/media-sources.json; run \`node scripts/build-media.mjs\` after changing it.\n\n` +
    `| Folder | Type | Author | Source | Licence |\n| --- | --- | --- | --- | --- |\n${rows.join('\n')}\n`,
);
console.log('done');
