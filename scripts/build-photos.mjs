// Downloads the photos listed in scripts/photo-sources.json once (into .cache/photos, not
// committed), then writes AVIF and WebP copies at fixed widths into public/images, the size
// manifest the app reads (src/data/photoManifest.ts) and public/images/CREDITS.md.
//
// Run: node scripts/build-photos.mjs   (re-run after editing photo-sources.json)
import { mkdir, readFile, writeFile, access } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const ROOT = path.resolve(import.meta.dirname, '..');
const CACHE = path.join(ROOT, '.cache', 'photos');
const OUT = path.join(ROOT, 'public', 'images');
const WIDTHS = [640, 1280, 1920, 2560];

const { photos, licence, checked } = JSON.parse(await readFile(path.join(ROOT, 'scripts', 'photo-sources.json'), 'utf8'));
const exists = (p) => access(p).then(() => true, () => false);

async function original(photo) {
  const file = path.join(CACHE, `${photo.key}.jpg`);
  if (await exists(file)) return file;
  // The largest version we use; Unsplash never enlarges past the original.
  const res = await fetch(`https://images.unsplash.com/photo-${photo.id}?w=2560&q=90&fm=jpg&fit=max`);
  if (!res.ok) throw new Error(`${photo.key}: download failed (${res.status})`);
  await writeFile(file, Buffer.from(await res.arrayBuffer()));
  return file;
}

async function build(photo) {
  const src = await original(photo);
  const meta = await sharp(src).metadata();
  const dir = path.join(OUT, photo.kind === 'entry' ? 'entry' : 'events');
  const widths = WIDTHS.filter((w) => w <= meta.width);
  if (widths.at(-1) !== meta.width && meta.width < WIDTHS.at(-1)) widths.push(meta.width);
  for (const w of widths) {
    const resized = sharp(src).resize({ width: w, withoutEnlargement: true });
    await resized.clone().avif({ quality: 50, effort: 4 }).toFile(path.join(dir, `${photo.key}-${w}.avif`));
    await resized.clone().webp({ quality: 72 }).toFile(path.join(dir, `${photo.key}-${w}.webp`));
  }
  return { key: photo.key, kind: photo.kind, width: meta.width, height: meta.height, widths };
}

await mkdir(CACHE, { recursive: true });
await mkdir(path.join(OUT, 'entry'), { recursive: true });
await mkdir(path.join(OUT, 'events'), { recursive: true });

const built = [];
for (let i = 0; i < photos.length; i += 4) {
  built.push(...(await Promise.all(photos.slice(i, i + 4).map(build))));
  console.log(`${Math.min(i + 4, photos.length)}/${photos.length}`);
}

const byKey = Object.fromEntries(photos.map((p) => [p.key, p]));
const manifest = Object.fromEntries(
  built.map((b) => [
    b.key,
    {
      dir: b.kind === 'entry' ? 'entry' : 'events',
      width: b.width,
      height: b.height,
      widths: b.widths,
      ...(byKey[b.key].position ? { position: byKey[b.key].position } : {}),
      ...(byKey[b.key].mobilePosition ? { mobilePosition: byKey[b.key].mobilePosition } : {}),
    },
  ]),
);

await writeFile(
  path.join(ROOT, 'src', 'data', 'photoManifest.ts'),
  `// Generated by scripts/build-photos.mjs from scripts/photo-sources.json. Do not edit by hand.\n` +
    `// Sizes are the largest generated file; every width exists as .avif and .webp in public/images.\n\n` +
    `export interface PhotoInfo {\n  dir: 'entry' | 'events';\n  width: number;\n  height: number;\n  widths: number[];\n  position?: string;\n  mobilePosition?: string;\n}\n\n` +
    `export const PHOTO_MANIFEST: Record<string, PhotoInfo> = ${JSON.stringify(manifest, null, 2)};\n`,
);

const rows = photos.map(
  (p) => `| \`${p.kind === 'entry' ? 'entry' : 'events'}/${p.key}-*\` | [${p.photographer}](${p.profile}) | [Unsplash photo page](${p.page}) | Unsplash License |`,
);
await writeFile(
  path.join(OUT, 'CREDITS.md'),
  `# Photo credits\n\nAll photos are from [Unsplash](https://unsplash.com) and used under the ${licence}. ` +
    `Each one was checked on its photo page on ${checked} ("Free to use under the Unsplash License", not Unsplash+). ` +
    `They are downloaded and served from this site, not hotlinked. The list is kept in scripts/photo-sources.json; ` +
    `run \`node scripts/build-photos.mjs\` after changing it.\n\n` +
    `| Files | Photographer | Source | Licence |\n| --- | --- | --- | --- |\n${rows.join('\n')}\n`,
);
console.log('done');
